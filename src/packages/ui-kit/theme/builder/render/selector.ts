// ============================================================================
// selector — трансляция SCSS-style `&` в финальный CSS-селектор.
// ============================================================================

/** SCSS-style `&` в селекторе: & -> base. Схлопываем дубли точек из `.&` */
export function buildSelector(key: string, base: string): string {
  return key.replace(/&/g, base).replace(/\.{2,}/g, '.')
}
